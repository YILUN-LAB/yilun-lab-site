import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdtemp, mkdir, readFile, writeFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import sharp from "sharp";

// Keep the original resolution, frame rate, colour and composition. Original
// clips remain available for comparisons; never overwrite their stable URLs.
const output = "public/assets/videos/optimized";
const temp = await mkdtemp(join(tmpdir(), "yilun-hero-"));
const assets = [];
await mkdir(output, { recursive: true });
try {
  for (let index = 1; index <= 3; index++) {
    const original = `/assets/videos/hero-${index}.mp4`;
    execFileSync("ffmpeg", [
      "-hide_banner",
      "-loglevel",
      "error",
      "-i",
      `public${original}`,
      "-map",
      "0:v:0",
      "-an",
      "-c:v",
      "libx264",
      "-preset",
      "slow",
      "-crf",
      "23",
      "-pix_fmt",
      "yuv420p",
      "-movflags",
      "+faststart",
      join(temp, `${index}.mp4`),
    ]);
    execFileSync("ffmpeg", [
      "-hide_banner",
      "-loglevel",
      "error",
      "-i",
      `public${original}`,
      "-frames:v",
      "1",
      join(temp, `${index}.png`),
    ]);
    await sharp(join(temp, `${index}.png`))
      .webp({ quality: 85 })
      .toFile(join(temp, `${index}.webp`));
    const asset = { original };
    for (const [key, extension] of [
      ["src", "mp4"],
      ["poster", "webp"],
    ]) {
      const bytes = await readFile(join(temp, `${index}.${extension}`));
      const hash = createHash("sha256").update(bytes).digest("hex").slice(0, 12);
      const name = `hero-${index}.${hash}.${extension}`;
      await writeFile(join(output, name), bytes);
      asset[key] = `/assets/videos/optimized/${name}`;
      asset[`${key}Bytes`] = bytes.length;
    }
    assets.push(asset);
  }
  await writeFile(
    "src/lib/hero-video-assets.ts",
    `// Generated by scripts/optimize-hero-videos.mjs.\nexport const HERO_VIDEO_ASSETS = ${JSON.stringify(assets, null, 2)} as const;\n`
  );
  console.table(assets);
} finally {
  await rm(temp, { recursive: true, force: true });
}
